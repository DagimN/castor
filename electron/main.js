const createWindow = () => {
  // Create the browser window.
  mainWindow = new BrowserWindow({
    height: 600,
    width: 800,
    icon: "./public/logo-mini.png",
    webPreferences: {
      preload: path.join(__dirname, "preload.js"),
      contextIsolation: true,
    },
  });

  if (app.isPackaged) {
    mainWindow.loadFile(path.join(__dirname, "../dist/index.html"));
  } else {
    mainWindow.loadURL("http://localhost:5173");
  }

  mainWindow.maximize();
  autoUpdater.checkForUpdatesAndNotify();
  appendHelpMenuItems();

  mainWindow.on("close", (event) => {
    projectorWindow?.destroy();
    projectorWindow = undefined;
    mainWindow = undefined;
  });
};

const createProjectorWindow = () => {
  if (!projectorWindow) {
    const displays = screen.getAllDisplays();

    const externalDisplay = displays.find((display) => {
      return display.bounds.x !== 0 || display.bounds.y !== 0;
    });

    // Create the browser window.
    projectorWindow = new BrowserWindow({
      icon: "./public/logo-mini.png",
      frame: false,
      transparent: false,
      fullscreen: true,
      x: externalDisplay?.bounds.x ?? 0,
      y: externalDisplay?.bounds.y ?? 0,
      webPreferences: {
        preload: path.join(__dirname, "preload.js"),
        contextIsolation: true,
      },
    });

    if (app.isPackaged) {
      projectorWindow.loadFile(path.join(__dirname, "../dist/index.html"), {
        hash: "/projector",
      });
    } else {
      projectorWindow.loadURL("http://localhost:5173/projector");
    }

    // projectorWindow.webContents.toggleDevTools();
    projectorWindow.on("close", (event) => {
      projectorWindow = undefined;
    });
  }
};

const createTutorialWindow = () => {
  if (tutorialWindow) {
    tutorialWindow.focus();
    return;
  }
  // Create the browser window.
  tutorialWindow = new BrowserWindow({
    height: 600,
    width: 800,
    icon: "./public/logo-mini.png",
    webPreferences: {
      preload: path.join(__dirname, "preload.js"),
      contextIsolation: true,
    },
  });

  if (app.isPackaged) {
    tutorialWindow.loadFile(path.join(__dirname, "../dist/index.html"), {
      hash: "/tutorial",
    });
  } else {
    tutorialWindow.loadURL("http://localhost:5173/tutorial");
  }

  tutorialWindow.setMenu(null);
  tutorialWindow.setMaximizable(false);

  tutorialWindow.on("close", (event) => {
    tutorialWindow = undefined;
  });
};

