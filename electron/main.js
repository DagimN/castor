ipcMain.handle("load-file", async (_, filePath) => {
  if (filePath.includes(".pdf")) {
    const folderPath = path.join(os.tmpdir(), "output");

    if (!fs.existsSync(folderPath)) {
      fs.mkdirSync(folderPath, { recursive: true });
    }

    const options = {
      format: "png",
      out_dir: folderPath,
      out_prefix: "page",
      page: null, // null = all pages
    };

    await convert(filePath, options);

    const imageFiles = fs
      .readdirSync(folderPath)
      .filter((f) => f.endsWith(".png"));

    const images = imageFiles.map((f) =>
      fs.readFileSync(path.join(folderPath, f)).toString("base64")
    );

    imageFiles.forEach((file) => fs.unlinkSync(path.join(folderPath, file)));

    return images;
  }

  const data = await fs.promises.readFile(filePath);

  return [data.toString("base64")];
});

ipcMain.handle("fetch-image-metadata", async (_, filePath) => {
  const buffer = fs.readFileSync(filePath);
  const parser = ExifParserFactory.create(buffer);
  const result = parser.parse();

  return result.imageSize;
});

ipcMain.handle("fetch-video-metadata", async (_event, filePath) => {
  return new Promise((resolve, reject) => {
    ffmpeg.ffprobe(filePath, (err, data) => {
      if (err) {
        reject(err);
      } else {
        resolve(data.format);
      }
    });
  });
});

